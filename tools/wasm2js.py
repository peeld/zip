#!/usr/bin/env python3
"""Wrap a .wasm file as an ES module for public/core/wasm.js.

    python3 tools/wasm2js.py path/to/codec.wasm [out.js]

Writes codec.wasm.js next to the input (or to out.js): a module whose default
export is the wasm bytes as base64. The page's CSP blocks fetch()
(connect-src 'none'), so this is how wasm gets in. Load it with
`loadWasm(new URL('./codec.wasm.js', import.meta.url))`.
"""
import base64
import hashlib
import sys
from pathlib import Path


def convert(src: Path, dst: Path) -> None:
    data = src.read_bytes()
    if data[:4] != b"\0asm":
        sys.exit(f"{src}: not a WebAssembly binary (no \\0asm header)")
    sha = hashlib.sha256(data).hexdigest()
    b64 = base64.b64encode(data).decode("ascii")
    dst.write_text(
        f"// Generated by tools/wasm2js.py from {src.name} ({len(data)} bytes,\n"
        f"// sha256 {sha}). Don't edit: regenerate from the .wasm.\n"
        f"export default '{b64}';\n",
        encoding="ascii",
    )


def main() -> None:
    if len(sys.argv) not in (2, 3):
        sys.exit(__doc__)
    src = Path(sys.argv[1])
    dst = Path(sys.argv[2]) if len(sys.argv) == 3 else src.with_name(src.name + ".js")
    convert(src, dst)
    print(f"wrote {dst}")


if __name__ == "__main__":
    main()
